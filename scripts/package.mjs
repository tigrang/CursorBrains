import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

export const cssPath = new URL('../dist/cursorbrains.css', import.meta.url);
export const scriptPath = new URL('../dist/cursorbrains.js', import.meta.url);
export const functionalityPath = new URL('../src/theme.js', import.meta.url);

export function createSnippet(css, functionality = '') {
  if (!css.trim()) {
    throw new Error('Compiled CSS is empty.');
  }

  return `// Generated by npm run build. Paste into the Cursor workbench DevTools console.
(() => {
  const css = ${JSON.stringify(css)};
  let style = document.getElementById('cursorbrains');

  if (!style) {
    style = document.createElement('style');
    style.id = 'cursorbrains';
    document.head.appendChild(style);
  }

  style.textContent = css;

${functionality.trimEnd()}

  console.log('CursorBrains applied');
})();
`;
}

export async function packageCss() {
  const [css, functionality] = await Promise.all([
    readFile(cssPath, 'utf8'),
    readFile(functionalityPath, 'utf8'),
  ]);
  await writeFile(scriptPath, createSnippet(css, functionality), 'utf8');
  console.log(`Created ${fileURLToPath(scriptPath)}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await packageCss();
}
